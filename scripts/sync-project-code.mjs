// Copies the Python source of the blessing-assist service into a JS
// module, so the project presentation page (/admin/project) can show the
// real code in a modal.
//
// Why a generated module and not fs.readFile at request time: on Vercel
// the Next.js service only ships the files its bundle traces. A string
// import is traced; a path built at runtime is not. Runs as `prebuild`,
// so every deployment carries the code it was built from. The generated
// file is committed too, so `next dev` shows it without an extra step.

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'blessing-assist-service')
const outFile = join(root, 'src', 'app', 'admin', 'project', 'pyCode.generated.js')

const FILES = ['app.py', 'prompts.py', 'gemini.py', 'prompt_lab.py', 'tests/test_prompts.py']

const entries = FILES.map(name => {
    const text = readFileSync(join(srcDir, name), 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '')
    return `    ${JSON.stringify(name)}: ${JSON.stringify(text)},`
})

const out = [
    '// GENERATED by scripts/sync-project-code.mjs - do not edit by hand.',
    '// Source of truth: blessing-assist-service/*.py',
    '/* eslint-disable */',
    'export const PY_CODE = {',
    ...entries,
    '}',
    '',
].join('\n')

writeFileSync(outFile, out)
console.log(`[sync-project-code] wrote ${FILES.length} files -> ${outFile}`)
